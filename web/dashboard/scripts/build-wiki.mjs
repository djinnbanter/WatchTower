const wikiDir = path.join(root, 'docs', 'wiki');
const esModuleOut = path.join(__dirname, '..', 'src', 'wiki', 'content.js');
const legacyOut = path.join(__dirname, '..', 'wiki-bundle.js');

const SKIP = new Set(['README.md', '_Sidebar.md', '_Footer.md']);

